import Foundation

/// One-way, re-runnable Obsidian export (spec §11.1). Produces a deterministic map of
/// vault-relative path → file contents, so re-exporting unchanged data changes nothing.
public struct ObsidianExporter: Sendable {
    public static let formatVersion = 1
    public static let header = "Generated by Grimoire. Edits here are overwritten on re-export; keep your own notes in a separate note that links here."

    public let library: DefinitionLibrary
    /// Off: Uranika charts keep the place name but not its coordinates (for vaults that sync elsewhere).
    public var includeCoordinates = true
    public init(library: DefinitionLibrary) { self.library = library }

    public func files(for data: GrimoireData) -> [String: String] {
        var out: [String: String] = [:]
        let volumeNames = Dictionary(uniqueKeysWithValues: data.volumes.map { ($0.id, $0.name) })
        let inquiryLinks = Dictionary(uniqueKeysWithValues: data.inquiries.map { ($0.id.string, Self.inquiryBase($0)) })
        var entryLinks = Dictionary(uniqueKeysWithValues: data.entries.map { ($0.id.string, Self.entryBase($0)) })
        entryLinks.merge(inquiryLinks) { a, _ in a }

        for e in data.entries where e.status == .filed {
            out[Self.entryPath(e)] = entry(e, volumes: volumeNames, links: entryLinks, inquiryLinks: inquiryLinks)
        }
        for i in data.inquiries {
            let related = data.entries.filter { $0.inquiryId == i.id && $0.status == .filed }.sorted { $0.id < $1.id }
            let reminders = data.reminders.filter { $0.targetId == i.id }.sorted { $0.id < $1.id }
            out["Inquiries/\(Self.inquiryBase(i)).md"] = inquiry(i, volumes: volumeNames, related: related, links: entryLinks, reminders: reminders)
        }
        for v in data.volumes {
            let refs = data.entries.filter { $0.physicalRef?.volumeId == v.id && $0.status == .filed }
            out["Volumes/\(Self.slug(v.name))-\(v.id).md"] = volume(v, entries: refs, links: entryLinks)
        }
        for d in library.decks where d.status != .template {
            out["Decks/\(d.id).md"] = deck(d)
        }
        return out
    }

    // MARK: Names

    public static func slug(_ s: String, max: Int = 48) -> String {
        let folded = Tokenizer.fold(s)
        var out = ""
        for ch in folded {
            if ch.isLetter || ch.isNumber { out.append(ch) } else if out.last != "-" { out.append("-") }
        }
        out = String(out.trimmingCharacters(in: CharacterSet(charactersIn: "-")).prefix(max))
        return out.trimmingCharacters(in: CharacterSet(charactersIn: "-"))
    }

    static func entryBase(_ e: Entry) -> String { "\(e.occurredAt.day)-\(e.type.rawValue)-\(e.id)" }
    static func entryPath(_ e: Entry) -> String {
        let parts = e.occurredAt.day.split(separator: "-")
        return "Entries/\(parts[0])/\(parts[1])/\(entryBase(e)).md"
    }
    static func inquiryBase(_ i: Inquiry) -> String {
        let s = slug(i.question)
        return "\(i.askedAt.day)-\(s.isEmpty ? "inquiry" : s)-\(i.id)"
    }
    static func wiki(_ base: String) -> String { "[[\(base)]]" }

    // MARK: Shared frontmatter pieces

    func timing(_ t: TimingContext?) -> [(String, YAMLValue)] {
        guard let t else { return [] }
        var m: [(String, YAMLValue)] = [
            ("moon_phase", .string(t.moonPhase.rawValue)),
            ("moon_illumination", .int(t.moonIllumination)),
            ("moon_sign", .string(t.moonSign.rawValue)),
            ("sun_sign", .string(t.sunSign.rawValue)),
        ]
        if let d = t.planetaryDay { m.append(("planetary_day", .string(d.rawValue))) }
        if let h = t.planetaryHour { m.append(("planetary_hour", .string(h.rawValue))) }
        if t.nearCusp { m.append(("near_cusp", .bool(true))) }
        return [("timing", .map(m))]
    }

    func astro(_ a: AstroSnapshot?) -> [(String, YAMLValue)] {
        guard let a else { return [] }
        var m: [(String, YAMLValue)] = [("source", .string(a.source)), ("status", .string(a.status.rawValue))]
        if let p = a.place {
            var pm: [(String, YAMLValue)] = []
            if let n = p.name { pm.append(("name", .string(n))) }
            if includeCoordinates { pm += [("lat", .double(p.latitude)), ("lon", .double(p.longitude))] }
            if !pm.isEmpty { m.append(("place", .map(pm))) }
        }
        if !a.points.isEmpty {
            let keys = UranianMath.order.filter { a.points[$0] != nil } + a.points.keys.filter { !UranianMath.order.contains($0) }.sorted()
            m.append(("points", .map(keys.map { ($0, .double(a.points[$0]!)) })))
        }
        if let v = a.asc { m.append(("asc", .double(v))) }
        if let v = a.mc { m.append(("mc", .double(v))) }
        if let n = a.natal { m.append(("natal", .map([("uranika_chart", .int(n.uranikaChart)), ("name", .string(n.name))]))) }
        if a.status == .computed {
            m.append(("settings", .map([("modulus", .double(a.settings.modulus)), ("orb", .double(a.settings.orb)), ("rate", .string(a.settings.rate))])))
        }
        if let v = a.solarArc { m.append(("solar_arc", .double(v))) }
        if !a.hits.isEmpty { m.append(("hits", .list(a.hits.map { .string($0.label) }))) }
        if let id = a.uranikaEvent { m.append(("uranika_event", .int(id))) }
        if let n = a.note { m.append(("note", .string(n))) }
        return [("astro", .map(m))]
    }

    func physical(_ p: PhysicalRef?, volumes: [ULID: String]) -> [(String, YAMLValue)] {
        guard let p else { return [] }
        return [("physical", .map([("volume", .str(volumes[p.volumeId] ?? p.volumeId.string)), ("page", .string(p.page))]))]
    }

    func linksYAML(_ links: [Link], _ map: [String: String]) -> [(String, YAMLValue)] {
        guard !links.isEmpty else { return [] }
        return [("links", .list(links.map { l in
            let target = l.kind == .vaultNote ? Self.wiki((l.target as NSString).deletingPathExtension) : map[l.target].map(Self.wiki) ?? l.target
            return .map([("type", .string(l.kind.rawValue)), ("target", .string(target))])
        }))]
    }

    // MARK: Entry

    func entry(_ e: Entry, volumes: [ULID: String], links: [String: String], inquiryLinks: [String: String]) -> String {
        var fm: [(String, YAMLValue)] = [
            ("id", .string(e.id.string)),
            ("type", .string(e.type.rawValue)),
            ("title", .string(e.displayTitle)),
            ("occurred_at", .string(e.occurredAt.iso8601)),
            ("time_zone", .string(e.occurredAt.timeZone)),
            ("tags", .list(e.tags.map { .string($0.path) })),
        ]
        if let iid = e.inquiryId { fm.append(("inquiry", .string(Self.wiki(inquiryLinks[iid.string] ?? iid.string)))) }
        fm += linksYAML(e.links, links)
        fm += physical(e.physicalRef, volumes: volumes)
        fm += timing(e.timing)
        fm += astro(e.astro)
        fm += typeFields(e)
        fm.append(("mode", .string(e.mode.rawValue)))
        if let c = e.captureId { fm.append(("capture_id", .string(c))) }
        if !e.attachments.isEmpty { fm.append(("attachments", .list(e.attachments.map { .string("_attachments/\($0.path)") }))) }
        fm.append(("grimoire_export_version", .int(Self.formatVersion)))

        var body = e.body.trimmingCharacters(in: .whitespacesAndNewlines)
        if let x = e.extraNotes, !x.isEmpty { body += "\n\n## Extra notes\n\n\(x)" }
        if let t = e.transcript, !t.isEmpty, t != e.body { body += "\n\n## Transcript\n\n\(t)" }
        for a in e.attachments where a.kind == .image { body += "\n\n![[_attachments/\(a.path)]]" }
        return YAML.frontmatter(.map(fm), comment: Self.header) + "\n" + body + "\n"
    }

    func typeFields(_ e: Entry) -> [(String, YAMLValue)] {
        let f = e.fields
        var m: [(String, YAMLValue)] = []
        func add(_ k: String, _ v: YAMLValue?) { if let v { m.append((k, v)) } }
        func s(_ x: String?) -> YAMLValue? { x.map { .string($0) } }
        func i(_ x: Int?) -> YAMLValue? { x.map { .int($0) } }
        func b(_ x: Bool?) -> YAMLValue? { x.map { .bool($0) } }
        func tags(_ x: [TagPath]?) -> YAMLValue? { x.map { .list($0.map { .string($0.path) }) } }
        for key in TypeFields.keys[e.type] ?? [] {
            switch key {
            case "intention": add("intention", s(f.intention))
            case "tools": add("tools", f.tools.map { .list($0.map { .string($0) }) })
            case "location": add("location", s(f.location))
            case "durationMin": add("duration_min", i(f.durationMin))
            case "steps": add("steps", s(f.steps))
            case "result": add("result", s(f.result))
            case "technique": add("technique", s(f.technique))
            case "depth": add("depth", i(f.depth))
            case "observations": add("observations", s(f.observations))
            case "setting": add("setting", s(f.setting))
            case "beings": add("beings", tags(f.beings))
            case "places": add("places", tags(f.places))
            case "clarity": add("clarity", i(f.clarity))
            case "being": add("being", s(f.being?.path))
            case "nature": add("nature", s(f.nature))
            case "communication": add("communication", s(f.communication))
            case "observedIn": add("observed_in", s(f.observedIn))
            case "interpretation": add("interpretation", s(f.interpretation))
            case "resolved": add("resolved", b(f.resolved))
            case "domain": add("domain", s(f.domain))
            case "lucid": add("lucid", b(f.lucid))
            case "recurring": add("recurring", b(f.recurring))
            case "figures": add("figures", tags(f.figures))
            default: break
            }
        }
        return m
    }

    // MARK: Inquiry

    func cardName(_ deckId: String?, _ cardId: String) -> String {
        deckId.flatMap(library.deck)?.card(cardId)?.name ?? cardId
    }

    func inquiry(_ i: Inquiry, volumes: [ULID: String], related: [Entry], links: [String: String], reminders: [Reminder]) -> String {
        var draws: [YAMLValue] = []
        var casts: [YAMLValue] = []
        for d in i.divinations.sorted(by: { $0.order < $1.order }) {
            for w in d.draws {
                draws.append(.map([("deck", .str(d.deckId)), ("card", .string(w.cardId)), ("name", .string(cardName(d.deckId, w.cardId))),
                                   ("position", .string(w.positionKey)), ("orientation", .string(w.orientation.rawValue))]))
            }
            if let c = d.cast {
                var m: [(String, YAMLValue)] = [("lines", .list(c.lines.map { .int($0) })),
                                                ("primary", .int(c.primaryHexagram(in: library.yijing))),
                                                ("changing", .list(c.changingLines.map { .int($0) }))]
                m.append(("resulting", c.resultingHexagram(in: library.yijing).map { .int($0) } ?? .null))
                m.append(("method", .string(c.method.rawValue)))
                casts.append(.map(m))
            }
        }
        var fm: [(String, YAMLValue)] = [
            ("id", .string(i.id.string)),
            ("type", .string("inquiry")),
            ("question", .string(i.question)),
            ("asked_at", .string(i.askedAt.iso8601)),
            ("time_zone", .string(i.askedAt.timeZone)),
            ("status", .string(i.status.rawValue)),
        ]
        if let c = i.category { fm.append(("category", .string(c.path))) }
        fm.append(("tags", .list(i.tags.map { .string($0.path) })))
        fm.append(("systems", .list(Array(Set(i.divinations.map { $0.deckId ?? $0.system.rawValue })).sorted().map { .string($0) })))
        if !draws.isEmpty { fm.append(("draws", .list(draws))) }
        if !casts.isEmpty { fm.append(("yijing", .list(casts))) }
        if let s = i.synthesis?.confidence { fm.append(("synthesis_confidence", .int(s))) }
        if let last = i.outcomes.last { fm.append(("fulfilled", .string(last.fulfilled.rawValue))) }
        if let r = reminders.first(where: { $0.status != .done }) { fm.append(("review_on", .string(r.dueOn))) }
        fm += physical(i.physicalRef, volumes: volumes)
        fm += timing(i.timing)
        fm.append(("grimoire_export_version", .int(Self.formatVersion)))

        var md = "# \(i.question)\n"
        if !i.context.isEmpty { md += "\n\(i.context.trimmingCharacters(in: .whitespacesAndNewlines))\n" }
        for d in i.divinations.sorted(by: { $0.order < $1.order }) {
            if let c = d.cast {
                let p = c.primaryHexagram(in: library.yijing)
                let ph = library.yijing.hexagram(p)
                md += "\n## Yi Jing (\(c.method.rawValue))\n\n"
                md += "Lines (bottom → top): \(c.lines.map(String.init).joined(separator: " "))\n\n"
                md += "- Primary: **\(p). \(ph?.name ?? "")** (\(ph?.pinyin ?? ""))\n"
                if !c.changingLines.isEmpty {
                    md += "- Changing lines: \(c.changingLines.map(String.init).joined(separator: ", "))\n"
                }
                if let r = c.resultingHexagram(in: library.yijing), let rh = library.yijing.hexagram(r) {
                    md += "- Resulting: **\(r). \(rh.name)** (\(rh.pinyin))\n"
                }
                md += "\n" + Self.hexagramDiagram(c) + "\n"
            } else {
                let deck = d.deckId.flatMap(library.deck)
                let spread = d.spreadId.flatMap(library.spread)
                md += "\n## \(deck?.name ?? d.deckId ?? "Cards") · \(spread?.name ?? d.spreadId ?? "Freeform")\n\n"
                if let m = d.method, !m.isEmpty { md += "Method: \(m)\n\n" }
                md += "| Position | Card | Orientation | Notes |\n|---|---|---|---|\n"
                for w in d.draws {
                    let pos = spread?.label(for: w.positionKey) ?? w.positionKey
                    md += "| \(Self.cell(pos)) | \(Self.cell(cardName(d.deckId, w.cardId))) | \(w.orientation.rawValue) | \(Self.cell(w.notes ?? "")) |\n"
                }
            }
            if let n = d.notes, !n.isEmpty { md += "\n\(n)\n" }
        }
        md += "\n## Synthesis\n\n\(i.synthesis?.body.trimmingCharacters(in: .whitespacesAndNewlines) ?? "_Not written yet._")\n"
        md += "\n## Outcomes\n\n"
        if i.outcomes.isEmpty { md += "_None recorded yet._\n" }
        for o in i.outcomes {
            md += "### \(o.recordedAt.day) · \(o.fulfilled.rawValue) · day \(i.daysAfter(o))\n\n\(o.body.trimmingCharacters(in: .whitespacesAndNewlines))\n\n"
        }
        if !related.isEmpty {
            md += "\n## Linked entries\n\n" + related.map { "- \(Self.wiki(links[$0.id.string]!)) (\($0.type.rawValue))" }.joined(separator: "\n") + "\n"
        }
        return YAML.frontmatter(.map(fm), comment: Self.header) + "\n" + md
    }

    static func cell(_ s: String) -> String { s.replacingOccurrences(of: "|", with: "\\|").replacingOccurrences(of: "\n", with: " ") }

    /// Text hexagram, top line first, changing lines marked.
    static func hexagramDiagram(_ c: YiJingCast) -> String {
        var rows: [String] = []
        for v in c.lines.reversed() {
            let line = YiJingCast.isYang(v) ? "━━━━━━━━━" : "━━━   ━━━"
            rows.append(line + (v == 9 ? "  ○" : v == 6 ? "  ×" : ""))
        }
        return "```\n" + rows.joined(separator: "\n") + "\n```\n"
    }

    // MARK: Volume and deck

    func volume(_ v: Volume, entries: [Entry], links: [String: String]) -> String {
        var fm: [(String, YAMLValue)] = [("id", .string(v.id.string)), ("type", .string("volume")), ("name", .string(v.name)),
                                         ("pagination", .string(v.pagination.rawValue))]
        if let s = v.startedOn { fm.append(("started_on", .string(s))) }
        if let e = v.endedOn { fm.append(("ended_on", .string(e))) }
        fm.append(("grimoire_export_version", .int(Self.formatVersion)))
        var md = "# \(v.name)\n\n"
        if let n = v.notes, !n.isEmpty { md += n + "\n\n" }
        md += "| Page | Entry |\n|---|---|\n"
        let sorted = entries.sorted { (($0.physicalRef?.pageRange?.lowerBound ?? 0), $0.id) < (($1.physicalRef?.pageRange?.lowerBound ?? 0), $1.id) }
        for e in sorted { md += "| \(Self.cell(e.physicalRef?.page ?? "")) | \(Self.wiki(links[e.id.string]!)) |\n" }
        return YAML.frontmatter(.map(fm), comment: Self.header) + "\n" + md
    }

    func deck(_ d: DeckDefinition) -> String {
        let fm: [(String, YAMLValue)] = [("id", .string(d.id)), ("type", .string("deck")), ("name", .string(d.name)),
                                         ("version", .int(d.version)), ("status", .string(d.status.rawValue)),
                                         ("card_count", .int(d.cards.count)), ("grimoire_export_version", .int(Self.formatVersion))]
        var md = "# \(d.name)\n\n"
        if d.cards.isEmpty { md += "_No cards defined yet._\n" }
        else {
            let attrs = d.attributes
            md += "| Id | Name | " + attrs.joined(separator: " | ") + " |\n|" + String(repeating: "---|", count: attrs.count + 2) + "\n"
            for c in d.cards {
                md += "| \(c.id) | \(Self.cell(c.name)) | " + attrs.map { Self.cell(c.attributes[$0]?.description ?? "") }.joined(separator: " | ") + " |\n"
            }
        }
        return YAML.frontmatter(.map(fm), comment: Self.header) + "\n" + md
    }
}

/// Writes export files, touching only files whose contents changed.
public struct ExportWriter {
    public struct Report: Equatable, Sendable {
        public var written: [String] = []
        public var unchanged: Int = 0
    }

    public static func write(_ files: [String: String], to root: URL) throws -> Report {
        var report = Report()
        let fm = FileManager.default
        for path in files.keys.sorted() {
            let url = root.appendingPathComponent(path)
            let data = Data(files[path]!.utf8)
            if let existing = try? Data(contentsOf: url), existing == data { report.unchanged += 1; continue }
            try fm.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
            try data.write(to: url, options: .atomic)
            report.written.append(path)
        }
        return report
    }
}
