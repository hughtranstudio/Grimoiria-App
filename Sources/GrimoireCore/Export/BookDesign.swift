import Foundation

/// A printed look: a folder holding `design.json` (page, type, colour, ornament settings) and,
/// optionally, `fonts/` and a `grimoire.typ` that overrides the shared layout. Designs are plain
/// files so they can be duplicated, edited and shared.
public struct BookDesign: Sendable, Identifiable {
    public static let bundledIDs = ["working-journal", "book-of-shadows"]

    public var id: String
    public var name: String
    public var description: String
    public var folder: URL

    struct Header: Decodable { var id: String; var name: String; var description: String? }

    public static func load(from folder: URL) throws -> BookDesign {
        let url = folder.appendingPathComponent("design.json")
        guard let data = try? Data(contentsOf: url) else { throw BookError.missingDesign(folder.path) }
        let h = try JSONDecoder().decode(Header.self, from: data)
        return BookDesign(id: h.id, name: h.name, description: h.description ?? "", folder: folder)
    }

    /// A bundled design by id, or a design folder by path.
    public static func named(_ nameOrPath: String) throws -> BookDesign {
        if bundledIDs.contains(nameOrPath) { return try load(from: bookResources.appendingPathComponent("Designs/\(nameOrPath)")) }
        return try load(from: URL(fileURLWithPath: nameOrPath))
    }

    static var bookResources: URL { Bundle.module.url(forResource: "Book", withExtension: nil)! }
    static var sharedTemplate: URL { bookResources.appendingPathComponent("grimoire.typ") }
}

public enum BookError: Error, CustomStringConvertible, Equatable {
    case missingDesign(String)
    case typstNotFound
    case typstFailed(String)

    public var description: String {
        switch self {
        case .missingDesign(let p): return "no design.json in \(p)"
        case .typstNotFound: return "typst not found; install it (brew install typst) or pass --typst PATH"
        case .typstFailed(let s): return "typst failed:\n\(s)"
        }
    }
}

/// Lays a book out as a self-contained Typst project folder:
/// `main.typ`, `grimoire.typ`, `book.json`, `design.json`, `images/`, `fonts/`.
/// The folder compiles on its own with `typst compile main.typ`, so it can be kept or shared.
public enum BookWriter {
    public static let mainSource = """
    // Generated by Grimoire. Compile with: typst compile --font-path fonts main.typ book.pdf
    #import "grimoire.typ": render
    #render(json("book.json"), json("design.json"))

    """

    public static func write(_ book: BookDocument, design: BookDesign, to root: URL, attachmentsRoot: URL?) throws {
        let fm = FileManager.default
        try fm.createDirectory(at: root, withIntermediateDirectories: true)
        try book.json().write(to: root.appendingPathComponent("book.json"))
        try Data(mainSource.utf8).write(to: root.appendingPathComponent("main.typ"))

        func replace(_ name: String, from src: URL) throws {
            let dst = root.appendingPathComponent(name)
            if fm.fileExists(atPath: dst.path) { try fm.removeItem(at: dst) }
            try fm.copyItem(at: src, to: dst)
        }
        try replace("design.json", from: design.folder.appendingPathComponent("design.json"))
        let override = design.folder.appendingPathComponent("grimoire.typ")
        try replace("grimoire.typ", from: fm.fileExists(atPath: override.path) ? override : BookDesign.sharedTemplate)
        let fonts = design.folder.appendingPathComponent("fonts")
        if fm.fileExists(atPath: fonts.path) { try replace("fonts", from: fonts) }

        if let attachmentsRoot, !book.images.isEmpty {
            try fm.createDirectory(at: root.appendingPathComponent("images"), withIntermediateDirectories: true)
            for (name, source) in book.images.sorted(by: { $0.key < $1.key }) {
                try replace(name, from: attachmentsRoot.appendingPathComponent(source))
            }
        }
    }
}

#if os(macOS) || os(Linux)
/// Runs the Typst compiler on a folder written by `BookWriter`.
public struct TypstRenderer: Sendable {
    public var executable: URL
    /// Extra font folders, searched before system fonts.
    public var fontPaths: [URL]

    public init(executable: URL, fontPaths: [URL] = []) { self.executable = executable; self.fontPaths = fontPaths }

    /// `typst` beside the running program (inside an app bundle), then on PATH, then Homebrew's prefixes.
    public static func locate(environment: [String: String] = ProcessInfo.processInfo.environment) -> URL? {
        var dirs: [String] = []
        if let here = Bundle.main.executableURL?.deletingLastPathComponent().path { dirs.append(here) }
        dirs += (environment["PATH"] ?? "").split(separator: ":").map(String.init)
        dirs += ["/opt/homebrew/bin", "/usr/local/bin", NSHomeDirectory() + "/.cargo/bin"]
        return dirs.map { URL(fileURLWithPath: $0).appendingPathComponent("typst") }
            .first { FileManager.default.isExecutableFile(atPath: $0.path) }
    }

    @discardableResult
    public func render(folder: URL, output: String = "book.pdf") throws -> URL {
        var args = ["compile"]
        let local = folder.appendingPathComponent("fonts")
        for f in [local] + fontPaths where FileManager.default.fileExists(atPath: f.path) { args += ["--font-path", f.path] }
        args += ["main.typ", output]
        let p = Process()
        p.executableURL = executable
        p.arguments = args
        p.currentDirectoryURL = folder
        let err = Pipe()
        p.standardError = err
        p.standardOutput = err
        try p.run()
        let log = err.fileHandleForReading.readDataToEndOfFile()
        p.waitUntilExit()
        guard p.terminationStatus == 0 else { throw BookError.typstFailed(String(decoding: log, as: UTF8.self)) }
        return folder.appendingPathComponent(output)
    }
}
#endif
