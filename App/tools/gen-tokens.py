#!/usr/bin/env python3
"""Design/tokens.json + the pinned Brand Codex -> every token file in both apps.

The Brand Codex (my-website brand/seed.json, Hugh's Master Brand Style) is the
source of the brand. Design/codex/tokens.json is a pinned copy of its generated
W3C tokens file; Design/tokens.json maps Codex roles onto the app and holds the
few app-only values. Never edit the outputs by hand.

Outputs:
  Sources/GrimoireAppKit/HouseTokens.swift                      Mac
  Design/tokens.css                                             proofs
  android/app/src/main/kotlin/.../capture/ui/CodexTokens.kt     Pixel
  android/app/src/main/res/values[-night]/codex_colors.xml      Pixel window ground

Usage: tools/gen-tokens.py           write every file
       tools/gen-tokens.py --check   exit 1 when a file is out of date or a text colour fails 4.5:1
"""
import json
import re
import sys
from pathlib import Path

here = Path(__file__).resolve().parent.parent
repo = here.parent
android_ui = repo / "android/app/src/main/kotlin/app/grimoiria/capture/ui"
android_res = repo / "android/app/src/main/res"
tokens = json.loads((here / "Design/tokens.json").read_text())
codex = json.loads((here / "Design/codex/tokens.json").read_text())
pin = tokens["$codex"]
if f"Brand Codex {pin['version']}." not in codex["$description"]:
    sys.exit(f"Design/codex/tokens.json is not Codex {pin['version']}: {codex['$description']}")


def hex6(value):
    """'#000' -> '#000000', upper case."""
    v = value.lstrip("#")
    if len(v) == 3:
        v = "".join(c * 2 for c in v)
    if not re.fullmatch(r"[0-9a-fA-F]{6}", v):
        raise ValueError(f"not a plain hex colour: {value}")
    return "#" + v.upper()


def codex_value(path, mode):
    """'hughtran.color.ink', 'night' -> '#EBE8DB', following {references}."""
    node = codex
    for part in path.split("."):
        node = node[part]
    value = node["$value"]
    if mode != "day":
        value = node.get("$extensions", {}).get("codex.modes", {}).get(mode, value)
    while value.startswith("{"):
        value = codex_value(value.strip("{}"), "day")
    return hex6(value)


def resolve(entry):
    if "codex" in entry:
        return codex_value(entry["codex"], entry.get("mode", "day"))
    return hex6(entry.get("legacy") or entry["app"])


palette = {k: resolve(v) for k, v in tokens["palette"].items()}
fonts = tokens["fonts"]
ROLES = ["ground", "surface", "ink", "muted", "rule", "rubric", "rubricText"]
GENERATED = f"Generated by tools/gen-tokens.py from Design/tokens.json and Brand Codex {pin['version']}. Do not edit."


def ink(ref):
    """'linen/0.62' -> (0xF4F4F4, 0.62)."""
    name, _, alpha = ref.partition("/")
    return int(palette[name].lstrip("#"), 16), float(alpha or 1)


def swift_ink(ref):
    if ref is None:
        return "nil"
    hex_, alpha = ink(ref)
    return f".init(0x{hex_:06X}, {alpha:g})" if alpha != 1 else f".init(0x{hex_:06X})"


def swift_str(value):
    return "nil" if value is None else json.dumps(value, ensure_ascii=False)


def swift_font(role):
    return swift_str(fonts[role]["family"] if role else None)


def swift_mode(mode):
    args = ", ".join(f"{r}: {swift_ink(mode.get(r))}" for r in ROLES)
    return f".init({args})"


def swift():
    t = tokens["type"]
    lines = [
        "// " + GENERATED,
        "",
        "/// The house style as plain data: colours, fonts, sizes and motion for",
        "/// each style option. UI/HouseStyle.swift turns it into SwiftUI.",
        "public enum HouseTokens {",
        "    public static let status = " + json.dumps(tokens["$status"], ensure_ascii=False),
        "",
        "    public enum Palette {",
    ]
    for name, hex_ in palette.items():
        lines.append(f"        public static let {name}: UInt32 = 0x{hex_.lstrip('#').upper()}")
    lines += ["    }", "", "    public enum Size {"]
    for key in ["caption", "callout", "body", "headline", "title3", "title2", "title"]:
        lines.append(f"        public static let {key}: Double = {t[key]:g}")
    lines += [
        "        /// Caps tracking for titles, as a share of the size.",
        f"        public static let titleTracking: Double = {t['titleTracking']:g}",
        "    }",
        "",
        "    public enum Motion {",
    ]
    for key, m in tokens["motion"].items():
        c = ", ".join(f"{x:g}" for x in m["curve"])
        lines.append(f"        /// {m['note']}")
        lines.append(f"        public static let {key} = HouseMotion(curve: ({c}), seconds: {m['seconds']:g})")
    lines += ["    }", "", "    public static let styles: [HouseStyleTokens] = ["]
    for sid, s in tokens["styles"].items():
        lines += [
            "        HouseStyleTokens(",
            f"            id: {json.dumps(sid, ensure_ascii=False)}, name: {json.dumps(s['name'], ensure_ascii=False)},",
            f"            summary: {json.dumps(s['summary'], ensure_ascii=False)},",
            f"            titleFont: {swift_font(s['titleFont'])}, textFont: {swift_font(s['textFont'])}, "
            f"labelFont: {swift_font(s['labelFont'])},",
            f"            titleCaps: {str(s['titleCaps']).lower()}, radius: {swift_str(s['radius'])}, "
            f"forceDark: {str(s['forceDark']).lower()}, accentIsRubric: {str(s['accentIsRubric']).lower()},",
            f"            light: {swift_mode(s['light'])},",
            f"            dark: {swift_mode(s['dark'])}),",
        ]
    lines += ["    ]", "}", ""]
    return "\n".join(lines)


def css_ink(ref):
    hex_, alpha = ink(ref)
    if alpha == 1:
        return f"#{hex_:06X}"
    return f"rgb({hex_ >> 16} {(hex_ >> 8) & 0xFF} {hex_ & 0xFF} / {alpha:g})"


def css():
    t = tokens["type"]
    out = [
        f"/* {GENERATED} */",
        ":root {",
    ]
    out += [f"  --ht-{k}: {v};" for k, v in palette.items()]
    out += [f"  --ht-font-{k}: \"{v['family']}\", serif;" for k, v in fonts.items() if k != "glyph"]
    out += [f"  --ht-size-{k}: {t[k]}px;" for k in ["caption", "callout", "body", "headline", "title3", "title2", "title"]]
    out += [f"  --ht-title-tracking: {t['titleTracking']}em;"]
    for key, m in tokens["motion"].items():
        out.append(f"  --ht-{key}: {m['seconds']}s cubic-bezier({', '.join(f'{x:g}' for x in m['curve'])});")
    out.append("}")
    for sid, s in tokens["styles"].items():
        for mode in ["light", "dark"]:
            if not s[mode]:
                continue
            out.append(f"[data-style=\"{sid}\"][data-mode=\"{mode}\"] {{")
            out += [f"  --{r}: {css_ink(s[mode][r])};" for r in ROLES if r in s[mode]]
            out.append("}")
    return "\n".join(out) + "\n"


def kotlin():
    out = [
        "// " + GENERATED,
        "package app.grimoiria.capture.ui",
        "",
        "import androidx.compose.ui.graphics.Color",
        "",
        "/** The house palette for the Pixel, from the Brand Codex through Design/tokens.json. Theme.kt maps it onto Material. */",
        "object Codex {",
    ]
    for name, entry in tokens["palette"].items():
        source = f"Codex {entry['codex']} ({entry.get('mode', 'day')})" if "codex" in entry else ("legacy" if "legacy" in entry else "app-only")
        out.append(f"    /** {entry['use']}. {source}. */")
        out.append(f"    val {name} = Color(0xFF{palette[name].lstrip('#')})")
    out += ["}", ""]
    return "\n".join(out)


def window_xml(mode):
    ground = tokens["styles"]["a"][mode]["ground"]
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"<!-- {GENERATED} -->\n"
        "<resources>\n"
        f"    <!-- Codex ground ({mode}): the window behind the app before Compose draws. -->\n"
        f'    <color name="window_ground">#FF{ink(ground)[0]:06X}</color>\n'
        "</resources>\n"
    )


def luminance(rgb):
    def ch(c):
        c /= 255
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    return 0.2126 * ch(rgb[0]) + 0.7152 * ch(rgb[1]) + 0.0722 * ch(rgb[2])


def rgb(ref, under=None):
    """A palette ref, with any alpha laid over the colour under it."""
    hex_, alpha = ink(ref)
    top = [(hex_ >> 16) & 255, (hex_ >> 8) & 255, hex_ & 255]
    if alpha == 1 or under is None:
        return top
    return [alpha * t + (1 - alpha) * u for t, u in zip(top, under)]


def contrast_failures():
    """Every text role on every ground in every style must read at 4.5:1 (WCAG AA), as the Codex checks."""
    failed = []
    for sid, s in tokens["styles"].items():
        for mode in ["light", "dark"]:
            m = s[mode]
            for ground in ["ground", "surface"]:
                if ground not in m:
                    continue
                g = rgb(m[ground])
                for text in ["ink", "muted", "rubricText"]:
                    if text not in m:
                        continue
                    a, b = sorted([luminance(rgb(m[text], g)), luminance(g)])
                    ratio = (b + 0.05) / (a + 0.05)
                    if ratio < 4.5:
                        failed.append(f"style {sid} {mode}: {text} on {ground} is {ratio:.2f}:1")
    return failed


outputs = {
    here / "Sources/GrimoireAppKit/HouseTokens.swift": swift(),
    here / "Design/tokens.css": css(),
    android_ui / "CodexTokens.kt": kotlin(),
    android_res / "values/codex_colors.xml": window_xml("light"),
    android_res / "values-night/codex_colors.xml": window_xml("dark"),
}
failures = contrast_failures()
for f in failures:
    print("FAIL contrast", f)
if "--check" in sys.argv:
    stale = [str(p.relative_to(repo)) for p, text in outputs.items() if not p.exists() or p.read_text() != text]
    if stale:
        print("out of date, run App/tools/gen-tokens.py:", ", ".join(stale))
    if stale or failures:
        sys.exit(1)
    print(f"PASS tokens up to date with Brand Codex {pin['version']}; every text colour reads at 4.5:1 or better")
else:
    for path, text in outputs.items():
        path.write_text(text)
        print("wrote", path.relative_to(repo))
    if failures:
        sys.exit(1)
