import XCTest
@testable import GrimoireCore

final class ExportTests: XCTestCase {
    let lib = TestSupport.library

    func sampleData() throws -> GrimoireData {
        let repo = MemoryRepository()
        let vol = Volume(id: ULID("01JBXA0000000000000000VA13")!, name: "Volume III")
        repo.save(vol)
        let asked = TestSupport.date("2026-10-28T08:14:00-07:00")
        var inq = Inquiry(id: ULID("01JBXA0000000000000000Q001")!, question: "Will the move go ahead?", askedAt: asked,
                          category: "question/home", tags: ["theme/threshold"], createdAt: asked.instant)
        inq.divinations = [
            Divination(id: ULID("01JBXA0000000000000000D001")!, system: .cards, deckId: "rws-tarot", spreadId: "three-card", performedAt: asked, order: 0, draws: [
                Draw(id: ULID("01JBXA0000000000000000W001")!, cardId: "cups-03", positionKey: "past", orientation: .reversed),
                Draw(id: ULID("01JBXA0000000000000000W002")!, cardId: "maj-16", positionKey: "present", notes: "sudden | shock"),
                Draw(id: ULID("01JBXA0000000000000000W003")!, cardId: "wands-11", positionKey: "future"),
            ]),
            Divination(id: ULID("01JBXA0000000000000000D002")!, system: .yijing, performedAt: asked, method: "coins", order: 1, cast: try YiJingCast(quick: "789677")),
        ]
        inq.synthesis = Synthesis(body: "Disruption, then news.", writtenAt: asked, confidence: 3)
        inq.addOutcome(Outcome(id: ULID("01JBXA0000000000000000T001")!, recordedAt: TestSupport.date("2026-11-04T10:00:00-08:00"), body: "Offer came.", fulfilled: .yes))
        inq.timing = TimingContext.compute(at: asked, location: nil)
        repo.save(inq)
        var omen = Entry(id: ULID("01JBXA0000000000000000E001")!, type: .omen, title: "Crow on the gate", occurredAt: asked, createdAt: asked.instant,
                         body: "A crow: \"waiting\" on the gate.\nThen it left.", tags: ["entity/crow", "theme/threshold"],
                         links: [Link(.fulfilledBy, to: inq.id), Link(.vaultNote, to: "Notes/Crows.md")], inquiryId: inq.id,
                         physicalRef: PhysicalRef(volumeId: vol.id, page: "42"), mode: .quick)
        omen.fields.observedIn = "nature"
        omen.fields.resolved = false
        omen.timing = TimingContext.compute(at: asked, location: GeoLocation(latitude: 37.77, longitude: -122.42))
        repo.save(omen)
        repo.save(Reminder(id: ULID("01JBXA0000000000000000R001")!, targetId: inq.id, dueOn: "2026-11-04", status: .done))
        return repo.data
    }

    func testEntryMarkdown() throws {
        let files = ObsidianExporter(library: lib).files(for: try sampleData())
        let path = "Entries/2026/10/2026-10-28-omen-01JBXA0000000000000000E001.md"
        let md = try XCTUnwrap(files[path], "\(files.keys.sorted())")
        XCTAssertTrue(md.hasPrefix("---\n# Generated by Grimoire."))
        XCTAssertTrue(md.contains("id: 01JBXA0000000000000000E001\n"))
        XCTAssertTrue(md.contains("type: omen\n"))
        XCTAssertTrue(md.contains("title: Crow on the gate\n"))
        XCTAssertTrue(md.contains("occurred_at: \"2026-10-28T08:14:00-07:00\"\n"))
        XCTAssertTrue(md.contains("tags: [entity/crow, theme/threshold]\n"))
        XCTAssertTrue(md.contains("inquiry: \"[[2026-10-28-will-the-move-go-ahead-01JBXA0000000000000000Q001]]\"\n"))
        XCTAssertTrue(md.contains("  - type: fulfilled-by\n    target: \"[[2026-10-28-will-the-move-go-ahead-01JBXA0000000000000000Q001]]\"\n"))
        XCTAssertTrue(md.contains("target: \"[[Notes/Crows]]\""))
        XCTAssertTrue(md.contains("physical:\n  volume: Volume III\n  page: \"42\"\n"))
        XCTAssertTrue(md.contains("observed_in: nature\n"))
        XCTAssertTrue(md.contains("planetary_day: mercury\n"))
        XCTAssertTrue(md.contains("grimoire_export_version: 1\n---\n"))
        XCTAssertTrue(md.hasSuffix("A crow: \"waiting\" on the gate.\nThen it left.\n"))
    }

    func testInquiryMarkdown() throws {
        let files = ObsidianExporter(library: lib).files(for: try sampleData())
        let md = try XCTUnwrap(files["Inquiries/2026-10-28-will-the-move-go-ahead-01JBXA0000000000000000Q001.md"])
        XCTAssertTrue(md.contains("question: \"Will the move go ahead?\"\n"))
        XCTAssertTrue(md.contains("draws:\n  - deck: rws-tarot\n    card: cups-03\n    name: Three of Cups\n    position: past\n    orientation: reversed\n"))
        XCTAssertTrue(md.contains("yijing:\n  - lines: [7, 8, 9, 6, 7, 7]\n    primary: 37\n    changing: [3, 4]\n    resulting: 25\n"))
        XCTAssertTrue(md.contains("status: resolved\n"))
        XCTAssertTrue(md.contains("fulfilled: yes\n") == false) // "yes" must be quoted so YAML keeps it a string
        XCTAssertTrue(md.contains("fulfilled: \"yes\"\n"))
        XCTAssertTrue(md.contains("| Recent past |") == false)
        XCTAssertTrue(md.contains("| Past | Three of Cups | reversed |  |"))
        XCTAssertTrue(md.contains("| Present | The Tower | upright | sudden \\| shock |"))
        XCTAssertTrue(md.contains("- Primary: **37. The Family**"))
        XCTAssertTrue(md.contains("- Resulting: **25. Innocence**"))
        XCTAssertTrue(md.contains("## Synthesis\n\nDisruption, then news.\n"))
        XCTAssertTrue(md.contains("### 2026-11-04 · yes · day 7"))
        XCTAssertTrue(md.contains("## Linked entries\n\n- [[2026-10-28-omen-01JBXA0000000000000000E001]] (omen)"))
    }

    func testVolumeAndDeckFiles() throws {
        let files = ObsidianExporter(library: lib).files(for: try sampleData())
        let vol = try XCTUnwrap(files["Volumes/volume-iii-01JBXA0000000000000000VA13.md"])
        XCTAssertTrue(vol.contains("| 42 | [[2026-10-28-omen-01JBXA0000000000000000E001]] |"))
        XCTAssertNotNil(files["Decks/rws-tarot.md"])
        XCTAssertNotNil(files["Decks/quareia.md"])
        XCTAssertNil(files["Decks/custom-template.md"])
    }

    func testReExportChangesNothing() throws {
        let data = try sampleData()
        let dir = TestSupport.tempDir()
        var files = ObsidianExporter(library: lib).files(for: data)
        files["grimoire.jsonl"] = try JSONLExporter(library: lib).export(data)
        let first = try ExportWriter.write(files, to: dir)
        XCTAssertEqual(first.written.count, files.count)
        var again = ObsidianExporter(library: lib).files(for: data)
        again["grimoire.jsonl"] = try JSONLExporter(library: lib).export(data)
        XCTAssertEqual(again, files)
        let second = try ExportWriter.write(again, to: dir)
        XCTAssertEqual(second.written, [])
        XCTAssertEqual(second.unchanged, files.count)
    }

    func testJSONLines() throws {
        let jsonl = try JSONLExporter(library: lib).export(try sampleData())
        let lines = jsonl.split(separator: "\n")
        XCTAssertEqual(lines.count, 4) // entry, inquiry, volume, reminder
        for l in lines { XCTAssertNoThrow(try JSONSerialization.jsonObject(with: Data(l.utf8))) }
        let inq = try JSONSerialization.jsonObject(with: Data(lines[1].utf8)) as! [String: Any]
        XCTAssertEqual(inq["record_type"] as? String, "inquiry")
        let derived = inq["derived"] as! [String: Any]
        XCTAssertEqual((derived["card_names"] as! [String: String])["rws-tarot/maj-16"], "The Tower")
        XCTAssertEqual(derived["outcome_days_after"] as? [Int], [7])
        // Round trip: the record itself decodes back into the model.
        struct Wrapper: Decodable { let record: Inquiry }
        let dec = JSONDecoder(); dec.dateDecodingStrategy = .iso8601
        XCTAssertEqual(try dec.decode(Wrapper.self, from: Data(lines[1].utf8)).record.divinations.count, 2)
    }

    func testYAMLQuoting() {
        XCTAssertEqual(YAML.quote("plain words"), "plain words")
        XCTAssertEqual(YAML.quote("no"), "\"no\"")
        XCTAssertEqual(YAML.quote("42"), "\"42\"")
        XCTAssertEqual(YAML.quote("1e5"), "\"1e5\"")
        XCTAssertEqual(YAML.quote("2026-10-28"), "\"2026-10-28\"")
        XCTAssertEqual(YAML.quote("01JBXA0000000000000000E001"), "01JBXA0000000000000000E001")
        XCTAssertEqual(YAML.quote("12v"), "12v")
        XCTAssertEqual(YAML.quote("a: b"), "\"a: b\"")
        XCTAssertEqual(YAML.quote("[[x]]"), "\"[[x]]\"")
        XCTAssertEqual(YAML.quote("say \"hi\"\nnow"), "\"say \\\"hi\\\"\\nnow\"")
        XCTAssertEqual(YAML.quote(""), "\"\"")
    }
}
